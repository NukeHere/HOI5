def country_identities(seed, count):
    rng = random.Random(seed ^ 0xC017)
    names, rulers = list(COUNTRY_NAMES), list(RULER_NAMES)
    rng.shuffle(names)
    rng.shuffle(rulers)
    return [(names[i % len(names)], rulers[i % len(rulers)]) for i in range(count)]
